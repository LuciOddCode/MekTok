        HotkeyKey.Left => "Left",
        HotkeyKey.Up => "Up",
        HotkeyKey.Right => "Right",
        HotkeyKey.Down => "Down",
        HotkeyKey.OemGrave => "`",
        HotkeyKey.OemMinus => "-",
        HotkeyKey.OemEqual => "=",
        HotkeyKey.OemLeftBracket => "[",
        HotkeyKey.OemRightBracket => "]",
        HotkeyKey.OemBackslash => "\\",
        HotkeyKey.OemSemicolon => ";",
        HotkeyKey.OemQuote => "'",
        HotkeyKey.OemComma => ",",
        HotkeyKey.OemPeriod => ".",
