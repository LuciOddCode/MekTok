    public static string ToDisplayString(this HotkeyKey key) => key switch
    {
        >= HotkeyKey.A and <= HotkeyKey.Z => ((char)('A' + (key - HotkeyKey.A))).ToString(),
        >= HotkeyKey.D0 and <= HotkeyKey.D9 => ((char)('0' + (key - HotkeyKey.D0))).ToString(),
        >= HotkeyKey.F1 and <= HotkeyKey.F24 => $"F{key - HotkeyKey.F1 + 1}",
        HotkeyKey.Space => "Space",
        HotkeyKey.Escape => "Esc",
        HotkeyKey.Enter => "Enter",
        HotkeyKey.Backspace => "Backspace",
        HotkeyKey.Tab => "Tab",
        HotkeyKey.Insert => "Insert",
        HotkeyKey.Delete => "Delete",
        HotkeyKey.Home => "Home",
        HotkeyKey.End => "End",
        HotkeyKey.PageUp => "PgUp",
